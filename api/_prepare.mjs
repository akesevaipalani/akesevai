import fs from 'node:fs';
import path from 'node:path';

const rootDir = process.cwd();
const builtHtmlPath = path.join(rootDir, 'dist', 'index.html');
const templateDir = path.join(rootDir, 'api', '_template');
const targetTemplatePath = path.join(templateDir, 'index.html');
const targetFallbackModulePath = path.join(templateDir, 'templateFallback.js');

if (!fs.existsSync(builtHtmlPath)) {
  console.error('Error: dist/index.html not found before Vercel SSR template preparation.');
  process.exit(1);
}

const builtHtml = fs.readFileSync(builtHtmlPath, 'utf8');
fs.mkdirSync(templateDir, { recursive: true });
fs.copyFileSync(builtHtmlPath, targetTemplatePath);
fs.writeFileSync(
  targetFallbackModulePath,
  `// Auto-generated by api/_prepare.mjs so packaged Vercel SSR functions always have the HTML shell.\nexport const SSR_TEMPLATE_HTML = ${JSON.stringify(builtHtml)};\n`,
  'utf8'
);
fs.unlinkSync(builtHtmlPath);

console.log('Prepared Vercel SSR shell at api/_template/index.html (+ templateFallback.js) and removed static dist/index.html');
